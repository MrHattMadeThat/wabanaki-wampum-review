// Builds src/map-data.js: SVG outlines of New Brunswick and its neighbours for the homelands map.
//
// Source: Natural Earth 1:50m admin-1 states and provinces (public domain).
//   https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_1_states_provinces.geojson
// Run: node scripts/build-map.mjs path/to/ne_50m_admin_1_states_provinces.geojson
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/build-map.mjs <ne_50m_admin_1_states_provinces.geojson>'); process.exit(1); }
const geo = JSON.parse(readFileSync(src, 'utf8'));

// The view: centred on New Brunswick, lon -70.0 .. -59.6, lat 43.4 .. 49.4, squashed by cos(47°) so shapes look right.
const BOX = { w: -70.0, e: -59.6, s: 43.4, n: 49.4 };
const K = Math.cos((47 * Math.PI) / 180);
const W = 1000;
const S = W / ((BOX.e - BOX.w) * K);
const H = Math.round((BOX.n - BOX.s) * S);
const project = ([lon, lat]) => [(lon - BOX.w) * K * S, (BOX.n - lat) * S];

function ringPath(ring) {
  const pts = [];
  for (const p of ring.map(project)) {
    const last = pts[pts.length - 1];
    if (!last || Math.hypot(p[0] - last[0], p[1] - last[1]) > 1.2) pts.push(p);
  }
  if (pts.length < 4) return '';
  const area = Math.abs(pts.reduce((a, p, i) => { const q = pts[(i + 1) % pts.length]; return a + p[0] * q[1] - q[0] * p[1]; }, 0) / 2);
  if (area < 6) return ''; // islands too small to see
  return 'M' + pts.map((p) => `${p[0].toFixed(1)} ${p[1].toFixed(1)}`).join('L') + 'Z';
}
function inBox(ring) {
  return ring.some(([lon, lat]) => lon > BOX.w - 1 && lon < BOX.e + 1 && lat > BOX.s - 1 && lat < BOX.n + 1);
}
function featurePath(name, keep = () => true) {
  const f = geo.features.find((x) => x.properties.name === name);
  if (!f) throw new Error(`no feature ${name}`);
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  return polys.filter((p) => inBox(p[0]) && keep(p[0])).map((p) => p.map(ringPath).join('')).join('');
}
const centreLat = (ring) => ring.reduce((a, p) => a + p[1], 0) / ring.length;
const polyPath = (pts) => 'M' + pts.map(project).map((p) => `${p[0].toFixed(1)} ${p[1].toFixed(1)}`).join('L') + 'Z';
const linePath = (pts) => 'M' + pts.map(project).map((p) => `${p[0].toFixed(1)} ${p[1].toFixed(1)}`).join('L');

const land = {
  nb: featurePath('New Brunswick'),
  ns: featurePath('Nova Scotia'),
  pe: featurePath('Prince Edward Island'),
  nf: featurePath('Newfoundland and Labrador', (r) => centreLat(r) < 51.7), // the island, not Labrador
  lab: featurePath('Newfoundland and Labrador', (r) => centreLat(r) >= 51.7),
  qc: featurePath('Québec'),
  me: featurePath('Maine'),
};

// Homelands, drawn in this order (later ones on top) and clipped to the coloured land.
// Boundaries follow the class map: Peskotomuhkati around Passamaquoddy Bay, Wolastoqewiyik up the Wolastoq
// (Saint John River) into Québec, Mi'kmaq everywhere else in the east. North edges run through open water so
// Québec's north shore and Labrador stay uncoloured.
const regions = {
  mikmaq: polyPath([
    [-71, 43], [-71, 47.6], [-69.8, 47.95], [-68.4, 48.7], [-66.5, 49.35], [-64.6, 49.6], [-61, 50.05], [-59.2, 50.2],
    [-57.6, 51.0], [-56.9, 51.38], [-55.5, 51.75], [-52, 51.9], [-52, 43],
  ]),
  wolastoqewiyik: polyPath([
    [-71, 45], [-71, 47.6], [-69.8, 47.95], [-68.4, 48.62], [-67.4, 47.9], [-66.6, 47.35], [-65.95, 46.6], [-65.55, 45.9],
    [-65.35, 45.4], [-65.6, 44.9], [-71, 44.9],
  ]),
  peskotomuhkatiyik: polyPath([
    [-67.95, 45.15], [-67.95, 45.8], [-67.3, 45.95], [-66.7, 45.85], [-66.25, 45.58], [-66.05, 45.3], [-66.2, 44.6], [-67.95, 44.6],
  ]),
};

// Places students know, to find their way around the map.
const places = {
  stGeorge: project([-66.83, 45.13]),
  wolastoq: linePath([[-66.06, 45.27], [-66.3, 45.55], [-66.64, 45.96], [-67.1, 46.0], [-67.58, 46.15], [-67.7, 46.6], [-67.74, 47.05], [-68.0, 47.25], [-68.33, 47.37], [-68.6, 47.25], [-69.05, 47.25]]),
  wolastoqLabel: project([-67.35, 46.35]),
  passamaquoddy: project([-67.0, 44.92]),
  fundy: project([-66.1, 44.55]),
  gulf: project([-63.4, 48.1]),
};

const out = `// Generated by scripts/build-map.mjs from Natural Earth (public domain). Don't edit by hand.
export const MAP = ${JSON.stringify({ w: W, h: H, proj: { w: BOX.w, n: BOX.n, kx: K * S, ky: S }, land, regions, places })};
`;
writeFileSync(new URL('../src/map-data.js', import.meta.url), out);
console.log(`src/map-data.js: ${W} x ${H}, ${(out.length / 1024).toFixed(0)} KB`);
